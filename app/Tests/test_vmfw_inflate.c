/*
 * S5LBox — DEFLATE and zlib expansion tests.
 *
 * The decoder these exercise is the one piece of the import path that reads a
 * length and then acts on it, so most of what follows is malformed on purpose.
 * Every named status in vmfw_inflate_status_t has at least one stream here
 * that produces it, and each of those streams is broken in exactly one way:
 * the zlib-header fixtures, for instance, keep FCHECK valid while corrupting
 * CM, so a decoder that only checked FCHECK would still fail this file.
 *
 * The two properties worth stating out loud, because both can be wrong while
 * every ordinary stream still expands correctly:
 *
 *   1. A back-reference is bounded by the bytes produced, not by the window.
 *      FX_DIST_MAX and FX_DIST_MAX_SHORT differ by one byte of output and use
 *      the identical distance of 32768; a decoder that asks "is the window
 *      full" accepts both, and the second one reads 32768 bytes that were
 *      never produced.
 *   2. expect_out is a bound. A member expanding to one byte more or one byte
 *      less than the container declared is refused, not clamped.
 *
 * The bulk fixtures are compared against a generator that runs in this file
 * rather than against an embedded copy of the plaintext, so 96 KiB of expected
 * output costs no source at all and the comparison is streaming.
 *
 * Copyright (c) 2026 j0shua-SYSON. MIT licensed.
 */
