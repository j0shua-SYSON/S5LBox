/*
 * These mirror the ones in the fixture generator exactly. A divergence shows
 * up as a byte-for-byte comparison failure, which is the point: the test data
 * is never stored, only regenerated, so the two halves have to agree.
 */

static uint8_t prng_byte(uint64_t i) {
    uint32_t x = (uint32_t)(i * UINT64_C(2654435761));
    x ^= x >> 15;
    x *= 2246822519u;
    x ^= x >> 13;
    x *= 3266489917u;
    x ^= x >> 16;
    return (uint8_t)x;
}

/* One of 32 eight-byte lowercase words, chosen by index. */
static uint8_t word_byte(uint64_t i) {
    unsigned w = prng_byte(i / 8u) & 31u;
    return (uint8_t)(0x61u + (prng_byte((uint64_t)w * 8u + (i % 8u) + 1u) % 26u));
}

/* Word soup with one run in eight replaced by incompressible noise. */
static uint8_t soup_byte(uint64_t i) {
    if ((i / 32u) % 8u == 7u) return prng_byte(i);
    return word_byte(i);
}

static uint8_t tiled_byte(uint64_t i);   /* needs FX_TILED_TILE, below */

static uint8_t letter_a(uint64_t i) { (void)i; return (uint8_t)'A'; }

/* ------------------------------------------------------------------------ */
/* Sources and sinks the decoder is meant to survive                         */
/* ------------------------------------------------------------------------ */

typedef uint8_t (*gen_fn)(uint64_t index);

/* Checks each byte as it arrives instead of storing it, so a 96 KiB
 * expectation needs no buffer. */
typedef struct {
    gen_fn   gen;
    uint64_t pos;
    uint64_t mismatches;
    uint64_t first_bad;
} gen_sink_t;

static bool gen_sink_write(void *ctx, const uint8_t *data, size_t len) {
    gen_sink_t *g = (gen_sink_t *)ctx;
    for (size_t i = 0; i < len; i++) {
        if (data[i] != g->gen(g->pos + (uint64_t)i)) {
            if (g->mismatches == 0u) g->first_bad = g->pos + (uint64_t)i;
            g->mismatches++;
        }
    }
    g->pos += (uint64_t)len;
    return true;
}

/* Refuses once it has taken `accept` bytes. */
typedef struct {
    uint64_t accept;
    uint64_t seen;
    unsigned refusals;
} stop_sink_t;

static bool stop_sink_write(void *ctx, const uint8_t *data, size_t len) {
    stop_sink_t *s = (stop_sink_t *)ctx;
    (void)data;
    if (s->seen + (uint64_t)len > s->accept) {
        s->refusals++;
        return false;
    }
    s->seen += (uint64_t)len;
    return true;
}

static size_t error_source(void *ctx, uint8_t *buf, size_t cap) {
    (void)ctx; (void)buf; (void)cap;
    return VMFW_SOURCE_ERROR;
}

/* Serves a prefix and then fails, so the error lands mid-stream rather than
 * on the very first read. */
typedef struct {
    vmfw_mem_source_t mem;
    size_t            ok_reads;
} late_error_source_t;

static size_t late_error_read(void *ctx, uint8_t *buf, size_t cap) {
    late_error_source_t *s = (late_error_source_t *)ctx;
    if (s->ok_reads == 0u) return VMFW_SOURCE_ERROR;
    s->ok_reads--;
    /* Capped, so `ok_reads` really is a prefix of the stream and not just the
     * whole thing handed over in one go. */
    return vmfw_mem_source_read(&s->mem, buf, cap < 64u ? cap : 64u);
}

/* Claims to have written more than the cap it was handed. */
static size_t lying_source(void *ctx, uint8_t *buf, size_t cap) {
    (void)ctx; (void)buf;
    return cap + 1u;
}

/* Hands over at most `bite` bytes per call, so every refill boundary in the
 * decoder gets walked over rather than being skipped by one big read. */
typedef struct {
    vmfw_mem_source_t mem;
    size_t            bite;
} drip_source_t;

static size_t drip_read(void *ctx, uint8_t *buf, size_t cap) {
    drip_source_t *d = (drip_source_t *)ctx;
    return vmfw_mem_source_read(&d->mem, buf, cap < d->bite ? cap : d->bite);
}

/* ------------------------------------------------------------------------ */
/* Shorthand                                                                 */
/* ------------------------------------------------------------------------ */

static void expect_status(vmfw_test_t *t, vmfw_inflate_status_t got,
                          vmfw_inflate_status_t want, const char *what) {
    VMFW_T_CHECK(t, got == want, "%s: got %d (%s), want %d (%s)", what,
                 (int)got, vmfw_inflate_strerror(got),
                 (int)want, vmfw_inflate_strerror(want));
}

/* Expand a raw stream into a throwaway buffer and report only the status. */
static vmfw_inflate_status_t raw_status(const uint8_t *src, size_t n) {
    uint8_t scratch[512];
    return vmfw_inflate_buffer(src, n, scratch, sizeof scratch,
                               VMFW_INFLATE_NO_EXPECTATION, NULL);
}

/* The same for a stream too big for a small buffer: count and discard. */
static vmfw_inflate_status_t raw_status_streamed(const uint8_t *src, size_t n,
                                                 uint64_t *produced) {
    vmfw_mem_source_t s;
    vmfw_null_sink_t  d = { 0 };
    vmfw_mem_source_init(&s, src, n);
    return vmfw_inflate(vmfw_mem_source_read, &s, vmfw_null_sink_write, &d,
                        VMFW_INFLATE_NO_EXPECTATION, produced);
}

static vmfw_inflate_status_t zlib_status(const uint8_t *src, size_t n) {
    uint8_t scratch[512];
    return vmfw_zlib_inflate_buffer(src, n, scratch, sizeof scratch,
                                    VMFW_INFLATE_NO_EXPECTATION, NULL);
}

