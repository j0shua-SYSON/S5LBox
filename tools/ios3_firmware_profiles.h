#define IOS3_FIRMWARE_PROFILE_COUNT \
    (sizeof ios3_firmware_profiles / sizeof ios3_firmware_profiles[0])

static inline const ios3_firmware_profile_t *ios3_firmware_profile_for_kernel(
        uint64_t size, const uint8_t sha256[32]) {
    if (!sha256) return NULL;
    for (size_t i = 0; i < IOS3_FIRMWARE_PROFILE_COUNT; i++) {
        const ios3_firmware_profile_t *p = &ios3_firmware_profiles[i];
        if (size == p->size[0] && !memcmp(sha256, p->sha256[0], 32)) return p;
    }
    return NULL;
}

/* Layout lookup only, for previously verified imports. This does not
 * authenticate file contents and must never replace component hashing. */
static inline const ios3_firmware_profile_t *ios3_firmware_profile_for_sizes(
        const uint64_t sizes[3]) {
    if (!sizes) return NULL;
    for (size_t i = 0; i < IOS3_FIRMWARE_PROFILE_COUNT; i++) {
        const ios3_firmware_profile_t *p = &ios3_firmware_profiles[i];
        if (!memcmp(sizes, p->size, sizeof p->size)) return p;
    }
    return NULL;
}
